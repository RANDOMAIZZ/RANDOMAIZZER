(function() {
    const quotes = [
        '«Я не ищу смысл жизни. Я ищу ощущение, что не зря трачу дни.»',
        '«0 + 1 = 10. Я — единица, которая ищет другую единицу.»',
        '«Ненормальный человек в нормальном обществе будет ненормальным.»',
        '«Люди могут уходить, даже если ты их ещё не видел.»',
        '«Я разговаривал с собой, с техникой и с тишиной.»',
        '«Я не искал славы. Я просто делал то, что мог.»',
        '«Я стал квантованным. Это легче, эффективнее и честнее.»',
        '«Иногда можно ничего не делать. Сидеть и слушать тишину.»',
        '«Я не ищу половинку. Я ищу другую единицу для нового разряда.»',
        '«Технарь с душой поэта.»',
    ];
    let qi = 0;
    window.nextQuote = function() {
        qi = (qi + 1) % quotes.length;
        const el = document.getElementById('rotating-quote');
        el.style.opacity = '0';
        el.style.transform = 'translateY(4px)';
        setTimeout(() => {
            el.textContent = quotes[qi];
            el.style.opacity = '1';
            el.style.transform = 'translateY(0)';
        }, 200);
    };
    setInterval(window.nextQuote, 6000);
})();
